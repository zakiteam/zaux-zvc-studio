import { phpDocText, phpString, phpValue } from './printer.js';
import { helpersTemplate } from './helpers.js';

// Prepares the pieces (`p`) used by the profile templates and writes the
// files of one unit. Text layout belongs to the templates in profile.js;
// this module only computes names, paths, requires and PHP literals.

// Relative path between two export files.
function relativePath(from, to) {
  const source = from.split('/').slice(0, -1);
  const target = to.split('/');
  let common = 0;
  while (common < source.length && source[common] === target[common]) common++;
  return [...source.slice(common).map(() => '..'), ...target.slice(common)].join('/');
}

function basePieces(profile, file, context = {}) {
  const indent = (text, levels = 1) => String(text).split('\n').map(line => line ? profile.indent.repeat(levels) + line : line).join('\n');
  const ref = name => profile.namespace ? `__NAMESPACE__ . ${phpString('\\' + name)}` : phpString(name);
  return {
    helpers: profile.helpers,
    externalHelpers: context.helpersPath === null ? profile.paths.helpers() : null,
    returns: profile.returns,
    emptyObject: profile.emptyObject,
    namespace: profile.namespace ? `\nnamespace ${profile.namespace};\n` : '',
    indent,
    ref,
    php: (value, depth = 0) => phpValue(value, { profile }, depth),
    guard: (name, body) => profile.guard ? `if (!function_exists(${ref(name)})) {\n${indent(body)}\n}` : body,
    header: lines => `<?php\n/**\n${lines.map(line => line ? ` * ${phpDocText(line)}` : ' *').join('\n')}\n *\n * Generated by Zaux Studio — PHP export profile v${profile.version}.\n */\n`,
    requireLines: paths => [...new Set(paths)].filter(path => path && path !== file)
      .map(path => `require_once __DIR__ . ${phpString('/' + relativePath(file, path))};`).join('\n')
  };
}

// Literal data files (meta, defaults, page data) never read $data: markers
// stay literal, and an empty top-level object stays a PHP array.
function dataPieces(profile, base) {
  return {
    ...base,
    php: (value, depth = 0) => value && typeof value === 'object' && !Array.isArray(value) && !Object.keys(value).length
      ? '[]' : phpValue(value, { profile, bindings: false }, depth)
  };
}

export function emitHelpers(profile, path) {
  return (profile.templates.helpers ?? helpersTemplate)(basePieces(profile, path));
}

// unit: { model, fn, dir, name, partials: [{ exportName, fn, entry }] }
export function emitComponent(unit, context) {
  const { profile } = context;
  const { model, fn, dir, name } = unit;
  const entry = dir + profile.paths.entry(model, name);
  const base = basePieces(profile, entry, context);
  const labels = { label: phpDocText(model.label), exportName: phpDocText(model.exportName), name, kind: model.kind };
  const files = {};
  files[entry] = profile.templates.component({
    ...base,
    ...labels,
    fn,
    native: model.native,
    snapshot: model.snapshot,
    metaPath: profile.paths.meta(model, name),
    defaultsPath: profile.paths.defaults(model, name),
    root: profile.shape[model.kind](model, model.nodes),
    partials: unit.partials,
    requires: base.requireLines([context.helpersPath, ...unit.partials.map(item => item.entry)])
  });
  const data = dataPieces(profile, base);
  files[dir + profile.paths.meta(model, name)] = profile.templates.meta({ ...data, ...labels, value: profile.meta(model) });
  files[dir + profile.paths.defaults(model, name)] = profile.templates.defaults({ ...data, ...labels, value: model.defaults });
  if (model.css.trim()) files[dir + profile.paths.css(model, name)] = model.css;
  return { entry, files };
}

// page: { template, fn, path, requires, entries: [{ label, fn, data } | { label, node }] }
export function emitPage(page, context) {
  const { profile } = context;
  const base = basePieces(profile, page.path, context);
  const literal = dataPieces(profile, base).php;
  return profile.templates.page({
    ...base,
    fn: page.fn,
    label: phpDocText(page.template.name),
    requires: base.requireLines([context.helpersPath, ...page.requires]),
    entries: page.entries.map(entry => ({
      label: phpDocText(entry.label),
      component: !entry.node,
      code: entry.node ? literal(entry.node, 0) : `${entry.fn}(${literal(entry.data, 0)}, $params)`
    }))
  });
}

export function emitReadme(context, summary) {
  const { profile } = context;
  const first = summary.main ?? null;
  const page = summary.pages?.[0] ?? null;
  const example = [
    ...(context.helpersPath ? [] : [`require_once __DIR__ . '/${profile.paths.helpers()}'; // load once, exported separately`]),
    ...(first ? [`require_once __DIR__ . '/${first.entry}';`] : []),
    ...(page ? [`require_once __DIR__ . '/${page.path}';`] : []),
    '',
    ...(first ? [`$node = ${first.fn}([/* field values */]);`, 'echo json_encode($node);'] : []),
    ...(page ? [`$nodes = ${page.fn}();`, 'echo json_encode($nodes);'] : [])
  ].join('\n');
  const files = Object.keys(context.files ?? {}).sort();
  return `# Zaux PHP export

PHP counterpart of the JavaScript ZVC/ZVP export (profile v${profile.version}). Each ZVC/ZVP is a function
that merges \`$data\` over its defaults and returns the Zaux runtime node, the same JSON as \`buildNode\`.
Render it on the front-end with Zaux's \`ComponentsRenderer\`.

| JavaScript | PHP |
| --- | --- |
| \`<Name>.zvc.js\` / \`.zvp.js\` | \`<Name>.zvc.php\` / \`.zvp.php\` |
| \`<Name>.meta.js\` | \`<Name>.meta.php\` |
| \`data/<Name>.defaults.js\` | \`data/<Name>.defaults.php\` |
| \`ZVCHelper.getValue\` / \`renderNode\` | \`${profile.helpers.getValue}\` / \`${profile.helpers.renderNode}\` in \`${profile.paths.helpers()}\` |
| \`_partials/<ExportName>/\` | \`_partials/<ExportName>/\` |

\`\`\`php
${example}
\`\`\`

## Files

${files.map(path => `- \`${path}\``).join('\n')}
`;
}
